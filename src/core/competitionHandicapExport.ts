import { Share } from 'react-native';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import * as FileSystem from 'expo-file-system/legacy';

export type HandicapExportPlayer = {
  name: string;
  handicapIndex: number | null;
  courseHandicap: number | null;
  playingHandicap: number | null;
};

export type HandicapExportTeam = {
  title: string;
  players: HandicapExportPlayer[];
  enteredCount: number;
  averageHandicapIndex: number | null;
  averagePlayingHandicap: number | null;
};

export type HandicapExportPayload = {
  title: string;
  generatedAt: string;
  courseName: string;
  teeName: string | null;
  courseRating: number | null;
  slopeRating: number | null;
  par: number | null;
  allowancePercent: number;
  roundingMode: 'round' | 'floor' | 'ceil';
  teamA: HandicapExportTeam;
  teamB: HandicapExportTeam;
};

const PLACEHOLDER_PLAYER_NAME = /^player\s*\d*$/i;

export function isRealHandicapPlayerName(name: string): boolean {
  const trimmed = name.trim();
  if (!trimmed) return false;
  return !PLACEHOLDER_PLAYER_NAME.test(trimmed);
}

export function isExportableHandicapPlayer(player: HandicapExportPlayer): boolean {
  if (isRealHandicapPlayerName(player.name)) return true;
  const hi = player.handicapIndex;
  if (hi == null || hi === 0) return false;
  return false;
}

export function filterExportableHandicapPlayers(
  players: HandicapExportPlayer[]
): HandicapExportPlayer[] {
  return players.filter(isExportableHandicapPlayer);
}

function average(values: number[]): number | null {
  if (!values.length) return null;
  const total = values.reduce((sum, v) => sum + v, 0);
  return Number((total / values.length).toFixed(1));
}

export function summarizeHandicapExportPlayers(players: HandicapExportPlayer[]): {
  enteredCount: number;
  averageHandicapIndex: number | null;
  averagePlayingHandicap: number | null;
} {
  const entered = filterExportableHandicapPlayers(players);
  return {
    enteredCount: entered.length,
    averageHandicapIndex: average(
      entered.map((p) => p.handicapIndex).filter((v): v is number => v != null)
    ),
    averagePlayingHandicap: average(
      entered.map((p) => p.playingHandicap).filter((v): v is number => v != null)
    ),
  };
}

function formatMaybe(value: number | null): string {
  return value == null ? '-' : String(value);
}

function formatRoundingModeLabel(mode: HandicapExportPayload['roundingMode']): string {
  if (mode === 'floor') return 'Floor';
  if (mode === 'ceil') return 'Ceil';
  return 'Round';
}

function safeFilenamePart(value: string): string {
  return value
    .trim()
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

function safe(value: string): string {
  return value.replace(/[&<>"']/g, (c) => {
    if (c === '&') return '&amp;';
    if (c === '<') return '&lt;';
    if (c === '>') return '&gt;';
    if (c === '"') return '&quot;';
    return '&#39;';
  });
}

function lineForPlayer(player: HandicapExportPlayer): string {
  return `${player.name.trim()} — HI ${formatMaybe(player.handicapIndex)} · CH ${formatMaybe(player.courseHandicap)} · PH ${formatMaybe(player.playingHandicap)}`;
}

function compactCourseLines(payload: HandicapExportPayload): string[] {
  const tee = payload.teeName?.trim() ? payload.teeName.trim() : '-';
  return [
    `Course: ${payload.courseName}    Tee: ${tee}`,
    `Rating: ${formatMaybe(payload.courseRating)}    Slope: ${formatMaybe(payload.slopeRating)}    Par: ${formatMaybe(payload.par)}`,
    `Allowance: ${payload.allowancePercent}%    Rounding: ${formatRoundingModeLabel(payload.roundingMode)}`,
  ];
}

function teamText(team: HandicapExportTeam): string {
  const players = filterExportableHandicapPlayers(team.players);
  const summary = summarizeHandicapExportPlayers(team.players);
  const lines = players.map((p) => `- ${lineForPlayer(p)}`);
  return [
    team.title,
    `Players entered: ${summary.enteredCount} · Avg HI: ${formatMaybe(summary.averageHandicapIndex)} · Avg PH: ${formatMaybe(summary.averagePlayingHandicap)}`,
    ...(lines.length ? lines : ['- No players entered']),
  ].join('\n');
}

export function buildCompetitionSummaryText(payload: HandicapExportPayload): string {
  return [
    payload.title,
    `Generated: ${new Date(payload.generatedAt).toLocaleString()}`,
    '',
    ...compactCourseLines(payload),
    '',
    teamText(payload.teamA),
    '',
    teamText(payload.teamB),
    '',
    'Generated by NetParGolf',
  ].join('\n');
}

function teamRowsHtml(team: HandicapExportTeam): string {
  const players = filterExportableHandicapPlayers(team.players);
  const summary = summarizeHandicapExportPlayers(team.players);
  const rows = players
    .map((p) => {
      const name = p.name.trim();
      return `<tr><td>${safe(name)}</td><td>${safe(formatMaybe(p.handicapIndex))}</td><td>${safe(formatMaybe(p.courseHandicap))}</td><td>${safe(formatMaybe(p.playingHandicap))}</td></tr>`;
    })
    .join('');

  const body =
    rows || '<tr><td colspan="4" style="text-align:center;color:#666">No players entered</td></tr>';

  return `
    <section class="team-section">
      <h2>${safe(team.title)}</h2>
      <p class="summary">Players entered: ${summary.enteredCount} · Avg HI: ${safe(
        formatMaybe(summary.averageHandicapIndex)
      )} · Avg PH: ${safe(formatMaybe(summary.averagePlayingHandicap))}</p>
      <table>
        <thead><tr><th>Name</th><th>HI</th><th>CH</th><th>PH</th></tr></thead>
        <tbody>${body}</tbody>
      </table>
    </section>
  `;
}

