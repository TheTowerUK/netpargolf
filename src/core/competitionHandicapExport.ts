export async function shareCompetitionSummary(payload: HandicapExportPayload): Promise<void> {
  const message = buildCompetitionSummaryText(payload);
  await Share.share({ message, title: payload.title });
}

function buildHandicapPdfFilename(payload: HandicapExportPayload): string {
  const safeCourse = safeFilenamePart(payload.courseName) || 'Course';
  const ymd = new Date(payload.generatedAt).toISOString().slice(0, 10).replace(/-/g, '');
  const teamALabel = payload.teamA.title.trim();
  const teamBLabel = payload.teamB.title.trim();
  const teamA = safeFilenamePart(teamALabel);
  const teamB = safeFilenamePart(teamBLabel);
  const hasCustomA = teamALabel.length > 0 && teamALabel !== 'Team A';
  const hasCustomB = teamBLabel.length > 0 && teamBLabel !== 'Team B';
  if (hasCustomA && hasCustomB) {
    return `NetParGolf_HandicapSheet_${safeCourse}_${teamA}_vs_${teamB}_${ymd}.pdf`;
  }
  if (hasCustomA) {
    return `NetParGolf_HandicapSheet_${safeCourse}_${teamA}_${ymd}.pdf`;
  }
  if (hasCustomB) {
    return `NetParGolf_HandicapSheet_${safeCourse}_${teamB}_${ymd}.pdf`;
  }
  return `NetParGolf_HandicapSheet_${safeCourse}_${ymd}.pdf`;
}

export async function exportCompetitionPdf(payload: HandicapExportPayload): Promise<string> {
  const html = buildCompetitionSummaryHtml(payload);
  const { uri } = await Print.printToFileAsync({ html });
  const dir = FileSystem.cacheDirectory ?? FileSystem.documentDirectory;
  const filename = buildHandicapPdfFilename(payload);
  const namedUri = dir ? `${dir}${filename}` : uri;
  if (dir) {
    await FileSystem.copyAsync({ from: uri, to: namedUri });
  }
  const shareOk = await Sharing.isAvailableAsync();
  if (!shareOk) return namedUri;
  await Sharing.shareAsync(namedUri, { mimeType: 'application/pdf' });
  return namedUri;
}

export async function saveCompetitionSummaryTextFile(payload: HandicapExportPayload): Promise<string> {
  const dir = FileSystem.cacheDirectory ?? FileSystem.documentDirectory;
  if (!dir) throw new Error('Storage not available');
  const filename = `netpargolf-handicap-summary-${Date.now()}.txt`;
  const uri = `${dir}${filename}`;
  await FileSystem.writeAsStringAsync(uri, buildCompetitionSummaryText(payload), {
    encoding: FileSystem.EncodingType.UTF8,
  });
  return uri;
}
